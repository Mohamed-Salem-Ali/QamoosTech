export const languages = [
  { code: 'ar', label: 'العربية', dir: 'rtl', ogLocale: 'ar_EG' },
  { code: 'en', label: 'English', dir: 'ltr', ogLocale: 'en_US' },
] as const

export type Lang = (typeof languages)[number]['code']
// Default language of the site (used by the root redirect). Arabic stays one click away.
export const defaultLang: Lang = 'en'

export function isLang(value: string): value is Lang {
  return languages.some((l) => l.code === value)
}

export function dirOf(lang: Lang) {
  return languages.find((l) => l.code === lang)!.dir
}

